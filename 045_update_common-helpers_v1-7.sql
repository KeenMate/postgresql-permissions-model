-- The original character class [^a-z0-9\-_] was written with a doubled backslash, so the
-- fragment \-_ was parsed as the range 0x5C..0x5F -- letting backslash, ']' and '^' pass
-- through unreplaced instead of being collapsed to the separator. The fix normalises every
-- run of non-alphanumeric characters to a single separator (matching the long-standing
-- behaviour where runs of spaces/punctuation collapse); the 'i' flag is dropped as redundant
-- because the text is already lower-cased.
create or replace function helpers.get_code(_text text, _separator text default '_')
    returns text
    immutable
    parallel safe
    cost 1
    language sql
as
$$
    -- removes accents (diacritic signs) from a given string --
with _unaccented as (select ext.unaccent(_text) as _title),
     -- lowercases the string
     _lowercase as (select lower(_title) as _title
                    from _unaccented),
     -- replaces every run of characters that is not a lowercase letter or number with the separator
     _hyphenated as (select regexp_replace(_title, '[^a-z0-9]+', _separator, 'g') as _title
                     from _lowercase),
     -- trims the separator if it exists on the head or tail of the string
     _trimmed as (select trim(BOTH _separator FROM _title) as _title
                  from _hyphenated)
select _title
from _trimmed;
$$;


