-- md5() only yields 32 hex characters, so the previous substring(md5(...), 0, len + 1) silently
-- capped the result at 32. Concatenate enough md5 blocks to cover len, then take the first len.
create or replace function helpers.random_string(len integer default 36)
    returns text
    volatile
    cost 1
    language sql
as
$$
select upper(substr(string_agg(md5(random()::text), ''), 1, len))
from generate_series(1, (len + 31) / 32);
$$;

