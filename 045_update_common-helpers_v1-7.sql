-- _trim selects the whitespace-trimming mode: 'both' (default), 'left', 'right', or 'none'
-- (any other value is treated as no trimming).
create function helpers.normalize_text(_text text, _lower_text boolean default true, _trim text default 'both')
    returns text
    immutable
    strict
    parallel safe
    cost 1
    language sql
as
$$
with normalized as (select case when _lower_text then lower(ext.unaccent(_text)) else ext.unaccent(_text) end as value)
select case lower(_trim)
           when 'both' then btrim(value)
           when 'left' then ltrim(value)
           when 'right' then rtrim(value)
           else value
       end
from normalized;
$$;


