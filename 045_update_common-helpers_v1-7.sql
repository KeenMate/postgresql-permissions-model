-- v1-2 declared this function STRICT, which makes PostgreSQL return null whenever ANY
-- argument is null -- before the body runs. That defeated the `_fields_to_delete is null
-- then return _data` branch (dead code) and, because _fields_to_delete defaults to null,
-- turned the single-argument call delete_jsonb_fields(data) into a silent data-nuking null.
-- Removing STRICT lets the existing body handle nulls as intended:
--   delete_jsonb_fields(data)            -> data unchanged (no-op)
--   delete_jsonb_fields(data, null)      -> data unchanged (no-op)
--   delete_jsonb_fields(null, fields)    -> null
create or replace function helpers.delete_jsonb_fields(_data jsonb, _fields_to_delete text[] default null)
    returns jsonb
    immutable
    parallel safe
    cost 0.05
    language plpgsql
as
$$
declare
    field    text;
    __result jsonb;
begin

    if _data is null then
        return null;
    elseif _fields_to_delete is null then
        return _data;
    end if;

    __result := _data;

    foreach field in array _fields_to_delete
        loop
            __result := __result - field;
        end loop;

    return __result;
end;
$$;


